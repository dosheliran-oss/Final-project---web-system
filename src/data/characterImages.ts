// Lookup table with lower-case keys, built once.
const imagesByLowerName = new Map(
  Object.entries(characterImages).map(([name, url]) => [name.toLowerCase(), url]),
)

// Returns the image URL for a character, or null if there is none.
export function getCharacterImage(name: string): string | null {
  return imagesByLowerName.get(name.trim().toLowerCase()) ?? null
}
